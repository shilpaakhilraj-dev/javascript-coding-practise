// Operators are symbols or keywords used to perform operations on values and variables.
// The values that an operator acts upon are called operands.
// For example, in the expression 5 + 3, the + is the operator and 5 and 3 are the operands
// Types:
// 1. Arithmetic Operators
// 2. Assignment Operators
// 3. Comparison Operators
// 4. Logical Operators
// 5. Bitwise Operators
// 6. Ternary Operators
// 7. Type Operators
// 8. Unary Operators
// 9. Relational Operators
// 10. String Operators

let a = 10;
let b = 3;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);
console.log(10 == "10");
console.log(10 === "10");
console.log(10 != "10");
console.log(10 !== "10");
console.log(true && false);
console.log(true || false);
console.log(!true);